namespace Ichigo.IchigoCode.Powers;

// Amount is the damage dealt to all enemies each time the owner loses HP; lasts the entire battle.
public sealed class EnhancedReflexesPower : IchigoPower
{
    public override PowerType Type => PowerType.Buff;

    public override PowerStackType StackType => PowerStackType.Counter;

    public override async Task AfterDamageReceived(
        PlayerChoiceContext choiceContext,
        Creature target,
        DamageResult result,
        ValueProp props,
        Creature? dealer,
        CardModel? cardSource)
    {
        if (target != Owner || result.UnblockedDamage <= 0)
            return;

        Flash();
        await CreatureCmd.Damage(choiceContext, Owner.CombatState!.HittableEnemies, Amount,
            ValueProp.Unpowered, Owner);
    }
}
